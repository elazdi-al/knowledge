/**
 * Generates exact Inter glyph-advance tables for the diagram text measurer.
 *
 * Downloads the static Inter TTFs (weights 400 and 700) from the Google Fonts
 * CSS API — the same family the site loads via next/font — reads each glyph's
 * advance width with opentype.js, and emits
 * `src/components/diagram/font-metrics.ts`.
 *
 * Run once (and re-run only if the glyph set below grows):
 *   bun scripts/gen-font-metrics.mjs
 */
import { writeFileSync } from "node:fs";
import opentype from "opentype.js";

const WEIGHTS = [400, 700];

// ASCII printable plus the math/notation glyphs that appear in diagram labels.
// Banned-from-output glyphs (en dash, bullet, arrows…) are still measured so
// the normalizer can reason about them if they ever sneak in via props.
const GLYPHS =
  Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join("") +
  "≥≤≠≈×÷±−–—…·•→←↔⇒⇐⋈σπδγλμθεΣΠΔΩ∞∅∈∉∪∩⊆⊥⌈⌉⌊⌋⟨⟩′″αβ†‖";

async function fontsForWeight(weight) {
  const css = await fetch(
    `https://fonts.googleapis.com/css2?family=Inter:wght@${weight}&display=swap`,
    { headers: { "User-Agent": "curl/8.0" } },
  ).then((r) => r.text());
  // one @font-face per unicode-range subset; merge them all for coverage
  const urls = [...css.matchAll(/url\((https:[^)]+\.ttf)\)/g)].map((m) => m[1]);
  if (!urls.length) throw new Error(`no ttf urls in css for weight ${weight}`);
  return Promise.all(
    urls.map(async (u) => opentype.parse(await fetch(u).then((r) => r.arrayBuffer()))),
  );
}

const tables = {};
for (const weight of WEIGHTS) {
  const fonts = await fontsForWeight(weight);
  const table = {};
  for (const ch of GLYPHS) {
    for (const font of fonts) {
      const glyph = font.charToGlyph(ch);
      if (glyph && glyph.index !== 0) {
        table[ch] =
          Math.round((glyph.advanceWidth / font.unitsPerEm) * 10000) / 10000;
        break;
      }
    }
  }
  tables[weight] = table;
  const missing = [...GLYPHS].filter((ch) => !(ch in table));
  if (missing.length) {
    console.warn(`weight ${weight}: missing glyphs ${missing.join(" ")}`);
  }
}

const avg = (t) => {
  const vals = Object.values(t);
  return Math.round((vals.reduce((a, b) => a + b, 0) / vals.length) * 10000) / 10000;
};

const out = `// AUTO-GENERATED by scripts/gen-font-metrics.mjs — do not edit by hand.
// Em-relative advance widths for Inter (the site font), per weight.
// Regenerate with: bun scripts/gen-font-metrics.mjs

export interface FontMetrics {
  /** advance width per glyph, as a fraction of the em (font size) */
  advances: Record<string, number>;
  /** fallback for glyphs outside the table */
  avg: number;
}

export const INTER_400: FontMetrics = {
  avg: ${avg(tables[400])},
  advances: ${JSON.stringify(tables[400])},
};

export const INTER_700: FontMetrics = {
  avg: ${avg(tables[700])},
  advances: ${JSON.stringify(tables[700])},
};
`;

writeFileSync(
  new URL("../src/components/diagram/font-metrics.ts", import.meta.url),
  out,
);
console.log("wrote src/components/diagram/font-metrics.ts");
