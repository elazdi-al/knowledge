/**
 * Data shapes for the figure engine. A Scene is the authored tree; a Frame is
 * the laid-out result. Both are plain JSON.
 */

export type Tone = "blue" | "teal" | "green" | "purple" | "red";
export const TONES: readonly Tone[] = ["blue", "teal", "green", "purple", "red"];

export type State = "default" | "active" | "placeholder" | "free" | "ghost" | "strong";
export const STATES: readonly State[] = ["default", "active", "placeholder", "free", "ghost", "strong"];

export type Side = "top" | "right" | "bottom" | "left";
export type Align = "start" | "center" | "end" | "stretch";
export type Dir = "row" | "col";
/** `diamond` and `triangle` (point down, label in the upper part) are the ER relationship and ISA glyphs; edges meet them at their vertices. */
export type Shape = "box" | "pill" | "circle" | "cylinder" | "diamond" | "triangle";
export const SHAPES: readonly Shape[] = ["box", "pill", "circle", "cylinder", "diamond", "triangle"];
export type TextSize = "title" | "label" | "note";
export type Weight = 400 | 500 | 600 | 700;

export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export type CellItem = {
  id?: string;
  label?: string;
  sub?: string;
  tone?: Tone;
  state?: State;
};

export type TableCell =
  | string
  | number
  | null
  | { text: string; tone?: Tone; solid?: boolean; mono?: boolean };

export interface TableRow {
  id?: string;
  cells: TableCell[];
  state?: State;
  tone?: Tone;
}

interface Base {
  id: string;
  state: State;
  tone?: Tone;
  /** Position inside a `Free` parent. */
  x?: number;
  y?: number;
}

export type Block = Base &
  (
    | {
        kind: "row" | "col";
        gap: number;
        align: Align;
        pad: number;
        /** a wrapping row becomes a column in the narrow layout of a static figure */
        wrap?: boolean;
        children: Block[];
      }
    | { kind: "grid"; cols: number; colGap: number; rowGap: number; align: Align; children: Block[] }
    | {
        kind: "group";
        title?: string;
        badge?: string;
        dir: Dir;
        gap: number;
        pad: number;
        align: Align;
        dashed?: boolean;
        children: Block[];
      }
    | { kind: "graph"; dir: "right" | "down"; gap: number; rankGap: number; children: Block[] }
    | { kind: "free"; children: Block[] }
    | { kind: "space"; w: number; h: number }
    | {
        kind: "node";
        title?: string;
        sub?: string;
        mono?: boolean;
        badge?: string;
        shape: Shape;
        /** second outline inset 4px (circle, box, diamond) */
        double?: boolean;
        /** rule under the title (ER key / partial key) */
        underline?: "solid" | "dashed";
        w?: number;
        h?: number;
        align?: "start" | "center";
      }
    | {
        kind: "cells";
        items: CellItem[];
        dir: Dir;
        /** lay the items out as a grid this many cells wide (one frame, dividers both ways) */
        cols?: number;
        cell?: number;
        mono: boolean;
        index?: boolean;
        ellipsis?: "start" | "end" | "both";
      }
    | { kind: "table"; columns?: string[]; rows: TableRow[]; mono: boolean; empty?: string }
    | {
        kind: "text";
        text: string;
        size: TextSize;
        muted?: boolean;
        mono?: boolean;
        weight?: Weight;
      }
    | { kind: "tag"; text: string }
    | { kind: "dots"; dir: Dir }
  );

export type Container = Extract<Block, { children: Block[] }>;
export const isContainer = (b: Block): b is Container => "children" in b;

export type RouteMode = "auto" | "straight" | "curve" | "ortho" | "arc";
export type EdgeState = "default" | "active" | "ghost";

export interface EdgeSpec {
  id: string;
  from: string;
  to: string;
  label?: string;
  dashed?: boolean;
  /** 2.5px stroke with a matching head (ER total participation) */
  thick?: boolean;
  head: "end" | "both" | "none";
  route: RouteMode;
  bend?: number;
  fromSide?: Side;
  toSide?: Side;
  loop?: Side;
  tone?: Tone;
  state: EdgeState;
}

export interface Scene {
  root: Block;
  edges: EdgeSpec[];
}

type DistOmit<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never;

/** Leaves generated by layout: one per cell / table row. */
export type DerivedLeaf = Base &
  (
    | { kind: "cell"; label?: string; sub?: string; mono: boolean; index?: number }
    | { kind: "trow"; cells: TableCell[]; mono: boolean }
  );

export type Item = (DistOmit<Block, "children" | "x" | "y"> | DerivedLeaf) & {
  rect: Rect;
  parent?: string;
};

export interface Frame {
  w: number;
  h: number;
  items: Item[];
  edges: EdgeSpec[];
}
